/**
 * Obtiene el ID de laudes para una fecha dada (por defecto hoy)
 * @param {Date} fecha 
 * @returns {string|null} ID de la salmodia (ej. "tos1lalu")
 */
export function obtenerIdLaudesPorFecha(fecha = new Date()) {
    const dia = fecha.getDate();
    const mes = fecha.getMonth() + 1;
    const anio = fecha.getFullYear();
    const clave = `${dia}/${mes}/${anio}`;
    return catalogoLaudes2026[clave] || null;
}
